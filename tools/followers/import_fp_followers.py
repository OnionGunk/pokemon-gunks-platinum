#!/usr/bin/env python3
"""Import Following Platinum's follower sprites and graphics tables into the decomp.

Credit: Following Platinum by Mikelan98 and collaborators. Everything here is taken directly from
their ROM: textures, the walk frame sequence, edited billboard models, and their table rows.

Usage: python import_fp_followers.py <repo root> <unpacked FP dir (C:/projects/pokemon-platinum-dexnav/fp)>
Requires the FP extraction outputs: fp_mmodel/*.bin, fp_gfx_tables.json, fp_follower_table.json.
"""
import json
import os
import shutil
import sys

repo, fpdir = sys.argv[1], sys.argv[2]
FIRST_GFX = 276
FIRST_MEMBER = 470          # FP's walk frame sequence; textures follow at 471+
FIRST_TEXTURE_MEMBER = 471

tables = json.load(open(os.path.join(fpdir, 'fp_gfx_tables.json')))
species_rows = json.load(open(os.path.join(fpdir, 'fp_follower_table.json')))
species_names = [l.strip() for l in open(os.path.join(repo, 'generated/species.txt')) if l.strip()]

textures = sorted((r for r in tables['textures'] if FIRST_GFX <= r['gfx'] < 4096), key=lambda r: r['gfx'])
num_gfx = len(textures)
for i, r in enumerate(textures):
    assert r['gfx'] == FIRST_GFX + i and r['narcIdx'] == FIRST_TEXTURE_MEMBER + i, r

# ---- name every follower graphics ID from FP's species table (base + gender or form offset)
names = {}
for row in species_rows:
    sp, base = row['species'], row['gfx']
    name = species_names[sp].replace('SPECIES_', '')
    names[base] = name
    if row['genderDiff']:
        names[base + 1] = name + '_F'
    for form in range(1, row['forms'] + 1):
        names[base + form] = f'{name}_FORM_{form}'
for g in range(FIRST_GFX, FIRST_GFX + num_gfx):
    names.setdefault(g, f'EXTRA_{g}')
gfx_names = [names[g] for g in range(FIRST_GFX, FIRST_GFX + num_gfx)]
assert len(set(gfx_names)) == len(gfx_names), 'duplicate follower names'

# ---- textures, frame sequence and the variant members, copied byte-for-byte
sprites_dir = os.path.join(repo, 'res/graphics/field_sprites')
out_dir = os.path.join(sprites_dir, 'followers')
os.makedirs(out_dir, exist_ok=True)
members = sorted(os.listdir(os.path.join(fpdir, 'fp_mmodel')))
member_files = []
for m in members:
    idx = int(m[:4])
    if idx == FIRST_MEMBER:
        fname = 'follower_walk.bin'
    elif idx < FIRST_TEXTURE_MEMBER + num_gfx:
        fname = 'follower_' + gfx_names[idx - FIRST_TEXTURE_MEMBER].lower() + '.nsbtx'
    else:
        fname = f'follower_variant_{idx:04d}.nsbtx'
    shutil.copyfile(os.path.join(fpdir, 'fp_mmodel', m), os.path.join(out_dir, fname))
    member_files.append(fname)

with open(os.path.join(out_dir, 'meson.build'), 'w', newline='\n') as f:
    f.write('# Generated by tools/followers/import_fp_followers.py (Following Platinum assets).\n')
    f.write('field_sprites_followers = copy_gen.process(files(\n')
    for fname in member_files:
        f.write(f"    '{fname}',\n")
    f.write('))\n')

# order: FP's members follow vanilla's 470 entries, keeping their indices
order_path = os.path.join(sprites_dir, 'field_sprites.order')
order = [l for l in open(order_path).read().splitlines() if l.strip()]
order = order[:FIRST_MEMBER]
assert len(order) == FIRST_MEMBER
open(order_path, 'w', newline='\n').write('\n'.join(order + member_files) + '\n')

# FP edited three vanilla billboard models; take their versions (members 421, 428, 429)
vanilla_mmodel = None
for idx, model in ((421, 'generic_32x32.nsbmd'), (428, 'generic_64x64.nsbmd'), (429, 'unknown_429.nsbmd')):
    src = os.path.join(fpdir, f'fp_edited_mmodel_{idx}.bin')
    if os.path.exists(src):
        shutil.copyfile(src, os.path.join(sprites_dir, 'models', model))

# ---- graphics IDs
gfx_txt = os.path.join(repo, 'generated/object_events_gfx.txt')
lines = open(gfx_txt).read().splitlines()
lines = [l for l in lines if not l.startswith('OBJ_EVENT_GFX_FOLLOWER_')]
at = lines.index('OBJ_EVENT_GFX_BERRY_SPROUT = 4096')
assert at == FIRST_GFX, f'vanilla graphics IDs must end at {FIRST_GFX - 1}'
lines[at:at] = ['OBJ_EVENT_GFX_FOLLOWER_' + n for n in gfx_names]
open(gfx_txt, 'w', newline='\n').write('\n'.join(lines) + '\n')

# ---- table rows (one include file per table, spliced in before each table's sentinel)
details = {d['gfx']: d for d in tables['details']}
anims = {a['gfx']: a for a in tables['anims']}
inc = os.path.join(repo, 'include/overlay005/followers')
os.makedirs(inc, exist_ok=True)
models = {0: 'GENERIC_32x32', 5: 'GENERIC_64x64'}
model_types = {0: 'NONE', 1: 'BILLBOARD', 2: '3D'}


def write_rows(name, rows):
    with open(os.path.join(inc, name), 'w', newline='\n') as f:
        f.write('// Generated by tools/followers/import_fp_followers.py from Following Platinum.\n')
        f.writelines(r + '\n' for r in rows)


write_rows('renderers.h', [f'    OBJ_EVENT_RENDERER(FOLLOWER_{n}, &sFollowerRenderer),' for n in gfx_names])
write_rows('textures.h', [f'    OBJ_EVENT_TEXTURE(FOLLOWER_{n}, follower_{n.lower()}_nsbtx),' for n in gfx_names])
write_rows('model_anims.h', [
    f'    OBJ_EVENT_MODEL_ANIM(FOLLOWER_{n}, {models[anims[g]["model"]]}, FOLLOWER, sFollowerBillboardAnims),'
    for g, n in zip(range(FIRST_GFX, FIRST_GFX + num_gfx), gfx_names)])
detail_rows = []
for g, n in zip(range(FIRST_GFX, FIRST_GFX + num_gfx), gfx_names):
    d = details[g]
    detail_rows.append(f'    OBJ_EVENT_DETAILS(FOLLOWER_{n}, {model_types[d["modelType"]]}, .hasShadow = {"TRUE" if d["hasShadow"] else "FALSE"}, '
                       f'.trackType = {d["trackType"]}, .hasReflection = {"TRUE" if d["hasReflection"] else "FALSE"}),')
write_rows('details.h', detail_rows)

# species -> base graphics ID, with FP's gender/form offsets
with open(os.path.join(repo, 'include/data/follower_species_gfx.h'), 'w', newline='\n') as f:
    f.write('// Generated by tools/followers/import_fp_followers.py from Following Platinum.\n')
    f.write('// Indexed by species: base follower graphics ID, whether females use base + 1,\n')
    f.write('// and how many alternate forms follow the base ID.\n')
    f.write('static const struct { u16 baseGfx; u8 genderDiff : 1; u8 numForms : 7; } sFollowerSpeciesGfx[] = {\n')
    for row in species_rows:
        f.write(f'    [{species_names[row["species"]]}] = {{ {row["gfx"]}, {row["genderDiff"]}, {row["forms"]} }},\n')
    f.write('};\n')

print(f'imported {num_gfx} follower graphics, {len(member_files)} archive members')
