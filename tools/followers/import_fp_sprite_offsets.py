"""Generate include/overlay005/followers/offsets.h from Following Platinum's per-sprite table
(fp_023c8340 reads it): 4 bytes per graphics ID - u16 gfx, then nibbles sideways / facing south /
facing north push-back in pixels and a size class (2 = 64x64 sprite).

Usage: python import_fp_sprite_offsets.py <fp_code.bin (FP's code blob, loaded at 0x023C8000)>
"""
import struct
import sys

BASE = 0x023C8000
FIRST_GFX = 276

blob = open(sys.argv[1], 'rb').read()
table = struct.unpack_from('<I', blob, 0x023C83AC - BASE)[0]
count = struct.unpack_from('<I', blob, 0x023C83B0 - BASE)[0]
rows = {}

for i in range(count):
    gfx, b2, b3 = struct.unpack_from('<HBB', blob, table - BASE + i * 4)
    rows[gfx] = (b2 & 15, b2 >> 4, b3 & 15, b3 >> 4)

assert sorted(rows) == list(range(FIRST_GFX, FIRST_GFX + count))
lines = [
    '// Generated by tools/followers/import_fp_sprite_offsets.py from Following Platinum (Mikelan98 et al.):',
    '// per-follower sprite push-back in pixels, indexed by graphics ID - 276.',
    '// { sideways, when facing south, when facing north, size class (2: 64x64 sprite) }',
    'static const u8 sFollowerSpriteOffsets[][4] = {',
]
lines += ['    { %d, %d, %d, %d },' % rows[g] for g in sorted(rows)]
lines.append('};')
open('include/overlay005/followers/offsets.h', 'w', newline='\n').write('\n'.join(lines) + '\n')
print(count, 'entries')
