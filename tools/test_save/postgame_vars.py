"""Generate the post-game story state for the test save.

Every variable that an automatic cutscene keys on (map frame triggers in scripts_init_*.s and step-on
coord events) is set to the highest value any script ever assigns it, i.e. its "story done" value.
Writes include/data/test_save_postgame_vars.h and prints variables that need a look by hand.
"""
import glob
import json
import re
from collections import defaultdict

ROOT = 'C:/src/pkplat-dexnav'
trigger_vals = defaultdict(set)

for path in glob.glob(f'{ROOT}/res/field/scripts/scripts_init_*.s'):
    for m in re.finditer(r'InitScriptGoToIf\w*\s+(VAR_\w+),\s*(\w+)', open(path).read()):
        trigger_vals[m.group(1)].add(m.group(2))

for path in glob.glob(f'{ROOT}/res/field/events/*.json'):
    for ev in json.load(open(path)).get('coord_events', []):
        var = ev.get('var')
        if isinstance(var, str) and var.startswith('VAR_'):
            trigger_vals[var].add(str(ev.get('value')))

set_vals = defaultdict(set)
for path in glob.glob(f'{ROOT}/res/field/scripts/*.s'):
    for m in re.finditer(r'\bSetVar\s+(VAR_\w+),\s*(\d+|TRUE|FALSE)\b', open(path).read()):
        set_vals[m.group(1)].add({'TRUE': 1, 'FALSE': 0}.get(m.group(2), None) if not m.group(2).isdigit() else int(m.group(2)))

# per-visit state machines (link rooms, facilities, minigames) must stay idle at 0
SESSION = ('LOAD_ACTION', 'MAP_LOCAL', 'SAFARI', 'PAL_PARK', 'BATTLE_TOWER', 'BATTLE_FRONTIER', 'COMMUNICATION',
           'WIFI', 'RESTAURANT', 'AMITY_SQUARE', 'FOLLOWER_MON')

rows, review = [], []
for var in sorted(trigger_vals):
    if any(k in var for k in SESSION):
        continue
    if not set_vals[var]:
        review.append(f'{var}: never set by a script (triggers on {sorted(trigger_vals[var])})')
        continue
    final = max(set_vals[var])
    # a toggle whose highest value is a trigger value is a temporary state that scripts reset to 0
    if str(final) in trigger_vals[var] or ('TRUE' in trigger_vals[var] and final == 1):
        review.append(f'{var}: left at 0 (highest value {final} triggers a scene)')
        continue
    rows.append((var, final))

with open(f'{ROOT}/include/data/test_save_postgame_vars.h', 'w', newline='\n') as f:
    f.write('// Generated by tools/test_save/postgame_vars.py: story variables at their final values, so no\n')
    f.write('// story cutscene auto-triggers in the test save.\n')
    f.write('static const u16 sTestPostgameVars[][2] = {\n')
    for var, final in rows:
        f.write(f'    {{ {var}, {final} }},\n')
    f.write('};\n')

print(f'{len(rows)} variables written')
print('\n'.join(review))
